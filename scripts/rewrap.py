#!/usr/bin/env python3
"""nixpkgs makeBinaryWrapper 로 감싼 bin/wine 을 runtime/ 용 셸 래퍼로 다시 만든다.

원래 래퍼는 nix store 의 bin/.wine 과 WINELOADER 를 절대경로로 박아 두기 때문에
runtime/ 오버레이를 우회한다. 래퍼에 내장된 makeCWrapper 인자를 읽어서
store 경로만 runtime 경로로 바꾼 동등한 셸 스크립트를 쓴다.

사용법: rewrap.py <vanilla 경로> <runtime 경로>   (래퍼가 아니면 아무것도 안 함, exit 0)
"""
import os
import shlex
import sys

vanilla, runtime = sys.argv[1].rstrip("/"), sys.argv[2].rstrip("/")
src = os.path.join(vanilla, "bin", "wine")
data = open(src, "rb").read().decode("utf-8", "replace")
start = data.find("makeCWrapper '")
if start < 0:
    sys.exit(0)

lines = []
for line in data[start:].splitlines():
    lines.append(line.rstrip("\\").strip())
    if not line.rstrip().endswith("\\"):
        break
args = shlex.split(" ".join(lines))[1:]

fix = lambda s: s.replace(vanilla, runtime)
target = fix(args.pop(0))
out = ["#!/bin/sh", "# generated by scripts/rewrap.py from " + src]
argv0 = '"$0"'
i = 0
while i < len(args):
    a = args[i]
    if a == "--inherit-argv0":
        i += 1
    elif a == "--argv0":
        argv0 = shlex.quote(args[i + 1]); i += 2
    elif a == "--set":
        out.append(f"export {args[i+1]}={shlex.quote(fix(args[i+2]))}"); i += 3
    elif a == "--set-default":
        out.append(f'export {args[i+1]}="${{{args[i+1]}-{fix(args[i+2])}}}"'); i += 3
    elif a == "--unset":
        out.append(f"unset {args[i+1]}"); i += 2
    elif a in ("--prefix", "--suffix"):
        var, sep, val = args[i + 1], args[i + 2], shlex.quote(fix(args[i + 3]))
        if a == "--prefix":
            out.append(f'export {var}={val}"${{{var}:+{sep}${var}}}"')
        else:
            out.append(f'export {var}="${{{var}:+${var}{sep}}}"{val}')
        i += 4
    else:
        sys.exit(f"rewrap.py: 모르는 makeCWrapper 인자 {a}")
out.append(f'exec -a {argv0} {shlex.quote(target)} "$@"')

dst = os.path.join(runtime, "bin", "wine")
if os.path.lexists(dst):
    os.remove(dst)
with open(dst, "w") as f:
    f.write("\n".join(out) + "\n")
os.chmod(dst, 0o755)
print(target)
